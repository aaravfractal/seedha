"""Stay invoices for consented guests (POLISH_BUILD B4, D-100).

Every amount is computed here by code from the guest's booking row, never by
an LLM (rule 1). GST is treated as included in what the guest paid:

    total_paid = list_amount - discount
    taxable    = total_paid * 10000 / (10000 + gst_bps), rounded to the rupee
    gst        = total_paid - taxable;  cgst = half of gst rounded;  sgst = rest

so taxable + cgst + sgst == total_paid exactly, and the total always equals
the booking row. Commission, GST on commission and fees are the hotel's own
costs and never appear on a guest's invoice.

Invoice numbers run per property and Indian financial year (April to March),
e.g. DEODAR/2627/0001, are created on the first request and reused after.
The sample hotel's invoices carry a "Sample" mark (rule 11).
"""

