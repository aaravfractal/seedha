import { test } from "node:test";
import assert from "node:assert/strict";
import { amountRows, bpsLabel, halfRateLabel, invoiceDate, invoicePdfPath } from "./invoice.ts";
import type { StayInvoice } from "./types-invoice.ts";

const SAMPLE: StayInvoice = {
  number: "DEODAR/2627/0001",
  filename: "stay-invoice-DEODAR-2627-0001.pdf",
  issued_on: "2026-10-13",
  sample: true,
  hotel_name: "Hotel Deodar View",
  hotel_address: "Mall Road, Mussoorie",
  gstin: null,
  guest_name: "Asha Rawat",
  check_in: "2026-09-20",
  check_out: "2026-09-22",
  nights: 2,
  room: "104 (Deluxe)",
  rate_per_night: 450_000,
  rate_is_average: false,
  room_charges: 900_000,
  discount: 50_000,
  taxable: 809_500,
  gst_bps: 500,
  cgst: 20_300,
  sgst: 20_200,
  total_paid: 850_000,
  payment_method: "Not recorded",
  lines: [],
  gst_note: "Prices include GST.",
  thank_you: "Thank you for staying with us",
  footer: "Generated by Seedha. Confirm the tax invoice format with your accountant.",
};

test("rate labels", () => {
  assert.equal(bpsLabel(500), "5%");
  assert.equal(bpsLabel(1800), "18%");
  assert.equal(bpsLabel(250), "2.5%");
  assert.equal(bpsLabel(0), "0%");
  assert.equal(halfRateLabel(500), "2.5%");
  assert.equal(halfRateLabel(1800), "9%");
  assert.equal(halfRateLabel(1200), "6%");
});

test("dates stay on the calendar day", () => {
  assert.equal(invoiceDate("2026-09-20"), "20 Sep 2026");
  assert.equal(invoiceDate("2027-04-01"), "1 Apr 2027");
});

test("amount rows format paise with Indian grouping and keep the API's numbers", () => {
  const rows = amountRows(SAMPLE);
  const byKey = Object.fromEntries(rows.map((r) => [r.key, r]));
  assert.equal(byKey.total?.value, "₹8,500");
  assert.equal(byKey.total?.strong, true);
  assert.equal(byKey.discount?.value, "−₹500");
  assert.equal(byKey.cgst?.label, "CGST at 2.5%");
  assert.equal(byKey.charges?.label, "Room charges, 2 nights");
  assert.equal(
    amountRows({ ...SAMPLE, discount: 0, nights: 1 }).find((r) => r.key === "discount")?.value,
    "₹0",
  );
  assert.equal(amountRows({ ...SAMPLE, rate_is_average: true })[0]?.label, "Average rate per night");
  for (const row of rows) {
    assert.ok(!/[!—]/.test(row.label + row.value), row.label);
  }
});

test("pdf path is same origin through the BFF", () => {
  assert.equal(invoicePdfPath(7), "/api/inbox/threads/7/invoice.pdf");
});
